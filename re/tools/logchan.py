#!/usr/bin/env python3
"""Build the Ne_Log channel gate table (log_channels.tsv) for the swofty_gamelog core mod.

  logchan.py --out <file>

Every Ne_Log_Thunk call site is gated inline by g_Ne_LogGate: the enabled byte, then a probe of the u32 hash set
for a constant per-site hash (`cmp r32, imm32; je <block that calls the logger>`). This walks every function that
calls the logger, pairs each probe hash with the channel string the gated block passes in rcx, and writes one row per
hash: `hash<TAB>sites<TAB>channel[,channel...]` (channels ordered by how many sites use them).
"""
import argparse, collections, hashlib, os, re, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kb
from pe_index import BASE, DATA, EXE, func_of, riprel_refs, rva2off
from capstone import CS_ARCH_X86, CS_MODE_64, Cs

GATE_ENABLED_OFF = 0x5d4


def names_addr(table, name):
    rows, _ = kb.read_table(table)
    for r in rows:
        if r['name'] == name:
            return int(r['addr'], 16)
    raise SystemExit(f'{name} not in {table}.tsv')


def cstr(va):
    o = rva2off(va - BASE)
    if o is None:
        return None
    b = bytes(DATA[o:o + 200]).split(b'\0')[0]
    try:
        s = b.decode('ascii')
    except UnicodeDecodeError:
        return None
    return s if s and all(32 <= ord(c) < 127 for c in s) else None


def rip_target(i):
    m = re.search(r'\[rip ([+-]) (0x[0-9a-f]+)\]', i.op_str)
    return i.address + i.size + int(m.group(2), 16) * (1 if m.group(1) == '+' else -1) if m else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    log = names_addr('functions', 'Ne_Log_Thunk')
    gate = names_addr('globals', 'g_Ne_LogGate')
    enabled = gate + GATE_ENABLED_OFF
    md = Cs(CS_ARCH_X86, CS_MODE_64)
    funcs = sorted({func_of(s) for s, _ in riprel_refs([log - BASE], '.xtls') if DATA[rva2off(s - 1)] == 0xE8} - {None})
    per = collections.defaultdict(collections.Counter)
    probes = calls = 0
    for f0, f1 in funcs:
        ins = list(md.disasm(bytes(DATA[rva2off(f0):rva2off(f0) + (f1 - f0)]), BASE + f0))
        at = {x.address: k for k, x in enumerate(ins)}
        if not any(rip_target(x) in (gate, enabled) for x in ins):
            continue
        for k in range(1, len(ins) - 1):
            c, j = ins[k], ins[k + 1]
            m = re.match(r'^(e[a-z]x|e[sd]i|e[sb]p|r\d+d), (0x[0-9a-f]+)$', c.op_str)
            if c.mnemonic != 'cmp' or not m or int(m.group(2), 16) <= 0xfff or j.mnemonic != 'je':
                continue
            if not any(re.search(r'dword ptr \[r\w+ \+ r\w+\*4\]', x.op_str) for x in ins[max(0, k - 4):k]):
                continue
            probes += 1
            h = int(m.group(2), 16)
            t = int(j.op_str, 16) if j.op_str.startswith('0x') else None
            if t not in at:
                per[h][None] += 1
                continue
            ch = None
            for x in ins[at[t]:at[t] + 60]:
                if x.mnemonic == 'lea' and x.op_str.startswith('rcx, [rip'):
                    ch = cstr(rip_target(x))
                if x.mnemonic == 'call' and x.op_str == hex(log):
                    calls += 1
                    break
                if x.mnemonic in ('ret', 'jmp'):
                    ch = None
                    break
            per[h][ch] += 1
    sha = hashlib.sha256(open(EXE, 'rb').read()).hexdigest()
    pe = struct.unpack_from('<I', bytes(DATA[0x3c:0x40]))[0]
    stamp = struct.unpack_from('<I', bytes(DATA[pe + 8:pe + 12]))[0]
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w') as f:
        f.write(f'# F1_25.exe {sha[:16]} {stamp}\n')
        f.write('# hash\tsites\tchannels (Ne_Log_Thunk gates, g_Ne_LogGate; generated by re/tools/logchan.py)\n')
        for h in sorted(per):
            names = [n.replace(',', ';') for n, _ in per[h].most_common() if n]
            f.write(f'{h:#010x}\t{sum(per[h].values())}\t{",".join(names) or "-"}\n')
    named = sum(1 for c in per.values() if any(c))
    print(f'logchan: {len(funcs)} functions, {probes} gate probes, {calls} reach Ne_Log_Thunk, {len(per)} hashes '
          f'({named} with a channel name) -> {a.out}')


if __name__ == '__main__':
    main()
