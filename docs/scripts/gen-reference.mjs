#!/usr/bin/env node
// Generates the Game API reference pages from bindings.json and the generated game headers.
//
//   node docs/scripts/gen-reference.mjs                         read native/ in this repository
//   node docs/scripts/gen-reference.mjs --root ../f1-modding    read another checkout
//   node docs/scripts/gen-reference.mjs --bindings <file> --include <dir>
//   node docs/scripts/gen-reference.mjs --check                 exit 1 when the pages are out of date
//   node docs/scripts/gen-reference.mjs --stub                  replace generated pages with the stub
//
// Inputs: <root>/native/dist/swofty/addons/core/bindings.json (or swofty/mods/core in older checkouts) and
// <root>/native/include/swofty/game/*.hpp.
// Outputs: docs/reference/game/*.md and docs/.vitepress/game-api.json (the Reference sidebar).
// Without bindings.json it writes a stub overview page and an empty sidebar, unless pages were already generated.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const docsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(docsDir, "reference", "game");
const sidebarFile = path.join(docsDir, ".vitepress", "game-api.json");
const marker = "<!-- Generated by docs/scripts/gen-reference.mjs. Do not edit by hand. -->";

const subsystemNotes = {
  core: "Engine helpers that other subsystems build on, such as making game strings.",
  fe_home: "The front-end home screen: its tiles and the commands its buttons raise.",
  fe_tiles: "Front-end tile lists and the items they hold.",
  vm: "View-model properties that connect game state to the UI.",
};

const kindTitles = {
  struct: "Structs",
  func: "Functions",
  data: "Data",
  vtable: "Virtual tables",
  call: "Call sites",
  site: "Patch sites",
};
const kindOrder = ["struct", "func", "data", "vtable", "call", "site"];

const primitives = new Set([
  "void", "bool", "char", "short", "int", "long", "float", "double", "signed", "unsigned",
  "int8_t", "uint8_t", "int16_t", "uint16_t", "int32_t", "uint32_t", "int64_t", "uint64_t",
  "size_t", "uintptr_t", "intptr_t",
]);
const qualifiers = new Set(["const", "volatile", "struct"]);

function parseArgs(argv) {
  const opts = { root: path.resolve(docsDir, ".."), check: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") opts.check = true;
    else if (a === "--stub") opts.stub = true;
    else if (a === "--root") opts.root = path.resolve(argv[++i]);
    else if (a === "--bindings") opts.bindings = path.resolve(argv[++i]);
    else if (a === "--include") opts.include = path.resolve(argv[++i]);
    else if (a === "--") continue;
    else throw new Error(`unknown argument ${a}`);
  }
  const core = (dir) => path.join(opts.root, "native", "dist", "swofty", dir, "core", "bindings.json");
  opts.bindings ??= fs.existsSync(core("mods")) && !fs.existsSync(core("addons")) ? core("mods") : core("addons");
  opts.include ??= path.join(opts.root, "native", "include", "swofty");
  return opts;
}

function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function parseTag(comment) {
  const level = comment?.match(/\bL\d\b/)?.[0] ?? null;
  const status = comment?.match(/\b(stable|experimental)\b/)?.[1] ?? null;
  return { level, status };
}

function parseHeaders(includeDir) {
  const gameDir = path.join(includeDir, "game");
  const structs = new Map();
  const opaque = new Set();
  let buildSha = null;
  if (!fs.existsSync(gameDir)) return { structs, opaque, buildSha };
  for (const file of fs.readdirSync(gameDir).filter((f) => f.endsWith(".hpp")).sort()) {
    const text = fs.readFileSync(path.join(gameDir, file), "utf8");
    const subsystem = path.basename(file, ".hpp");
    if (subsystem === "base") {
      buildSha = text.match(/build_sha256\[\]\s*=\s*"([0-9a-f]+)"/)?.[1] ?? null;
      for (const m of text.matchAll(/^struct (\w+);$/gm)) opaque.add(m[1]);
      continue;
    }
    for (const m of text.matchAll(/^struct (\w+) \{\n([\s\S]*?)^\};/gm)) {
      const [, name, body] = m;
      const fields = [];
      for (const line of body.split("\n")) {
        const f = line.match(/^\s*(.+?[\s*&])\s*(\w+)\s*(\[[^\]]*\])?;\s*(?:\/\/\s*(.*))?$/);
        if (!f || f[2].startsWith("_pad")) continue;
        fields.push({ type: f[1].trim(), name: f[2], array: f[3] ?? "", ...parseTag(f[4]) });
      }
      for (const o of text.matchAll(new RegExp(`offsetof\\(${name}, (\\w+)\\) == (0x[0-9a-fA-F]+)`, "g"))) {
        const field = fields.find((x) => x.name === o[1]);
        if (field) field.offset = o[2];
      }
      structs.set(name, { kind: "struct", id: name, subsystem, fields });
    }
  }
  for (const name of structs.keys()) opaque.delete(name);
  return { structs, opaque, buildSha };
}

function splitProto(b) {
  const m = b.proto?.match(new RegExp(`^(.+?)\\s*\\b${b.id}\\s*\\((.*)\\)$`));
  if (!m || m[2].includes("(")) return null;
  const params = m[2].trim() === "" || m[2].trim() === "void" ? [] : m[2].split(",").map((p) => {
    const pm = p.trim().match(/^(.*?[\s*&])(\w+)$/);
    return pm ? { type: pm[1].trim(), name: pm[2] } : { type: p.trim(), name: "" };
  });
  return { ret: m[1].trim(), params };
}

function typeHtml(type, ctx) {
  return type
    .split(/(\s+|\*|&)/)
    .filter((t) => t !== "")
    .map((tok) => {
      if (/^\s+$/.test(tok)) return " ";
      if (tok === "*" || tok === "&") return `<span class="punct">${tok}</span>`;
      if (qualifiers.has(tok)) return `<span class="keyword">${tok}</span>`;
      if (primitives.has(tok)) return `<span class="type pod">${tok}</span>`;
      const target = ctx.structs.get(tok);
      if (target) {
        const href = target.subsystem === ctx.subsystem ? `#${tok}` : `${target.subsystem}.html#${tok}`;
        return `<a class="class name" href="${href}">${tok}</a>`;
      }
      return `<span class="struct name">${esc(tok)}</span>`;
    })
    .join("")
    .replace(/ (<span class="punct">[*&]<\/span>)/g, "$1");
}

function tagsHtml(e) {
  const tags = [];
  if (e.status) tags.push(`<span class="tag status-${e.status}">${e.status}</span>`);
  if (e.level) tags.push(`<span class="tag">${e.level}</span>`);
  if (e.rva) tags.push(`<span class="tag">rva ${esc(e.rva)}</span>`);
  if (e.slots) tags.push(`<span class="tag">${e.slots} slots</span>`);
  if (e.cxx) tags.push(`<span class="tag cxx">${esc(e.cxx)}</span>`);
  return tags.length ? `<div class="tags">${tags.join("")}</div>` : "";
}

function entityHtml(e, ctx) {
  if (e.kind === "struct") {
    const rows = e.fields.map((f) => {
      const off = `<span class="offset">${f.offset ?? ""}</span>`;
      const st = f.status ? ` <span class="tag status-${f.status}">${f.status}</span>` : "";
      return `<div class="member">${off}${typeHtml(f.type, ctx)} <span class="field">${f.name}</span>${esc(f.array)}<span class="punct">;</span>${st}</div>`;
    });
    const body = rows.length ? `<div class="members">${rows.join("")}</div>` : "";
    return `<div class="entity struct" id="${e.id}"><div class="class-decl"><span class="keyword">struct</span> <span class="class name">${e.id}</span> <span class="punct">{</span></div>${body}<div class="class-decl"><span class="punct">};</span></div></div>`;
  }
  if (e.kind === "func") {
    const p = splitProto(e);
    const sig = p
      ? `${typeHtml(p.ret, ctx)} <span class="name">${e.id}</span><span class="punct">(</span>${p.params
          .map((x) => `<span class="param">${typeHtml(x.type, ctx)}${x.name ? ` <span class="param-name">${x.name}</span>` : ""}</span>`)
          .join('<span class="punct">, </span>')}<span class="punct">)</span>`
      : `<span class="name">${esc(e.proto ?? e.id)}</span>`;
    return `<div class="entity fun" id="${e.id}"><div class="function-signature">${sig}</div>${tagsHtml(e)}</div>`;
  }
  if (e.kind === "data") {
    return `<div class="entity var" id="${e.id}"><div class="function-signature">${typeHtml(e.type ?? "void *", ctx)} <span class="name var-name">${e.id}</span></div>${tagsHtml(e)}</div>`;
  }
  return `<div class="entity ${e.kind}" id="${e.id}"><div class="function-signature"><span class="keyword">${e.kind}</span> <span class="name">${e.id}</span></div>${tagsHtml(e)}</div>`;
}

const chevron =
  '<svg class="chevron" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="m9 6 6 6-6 6"/></svg>';

function subsystemPage(sub, entries, ctx, source) {
  const lines = [
    "---",
    `title: ${sub}`,
    `description: Functions and structs in the ${sub} subsystem of the F1 25 game API.`,
    "---",
    "",
    marker,
    "",
    `# <span class="entity-kind">Subsystem</span> ${sub}`,
    "",
    `<div class="include"><code><span class="keyword">#include</span> <span class="string">&lt;swofty/game/${sub}.hpp&gt;</span></code></div>`,
    "",
  ];
  if (subsystemNotes[sub]) lines.push(subsystemNotes[sub], "");
  for (const kind of kindOrder) {
    const list = entries.filter((e) => e.kind === kind);
    if (!list.length) continue;
    lines.push(
      `<details class="section" open><summary><span>${chevron}${kindTitles[kind]}<span class="badge">${list.length}</span></span></summary><div>${list
        .map((e) => entityHtml(e, ctx))
        .join("")}</div></details>`,
      "",
    );
  }
  lines.push(`Generated from \`${source}\` for build \`${ctx.build.slice(0, 12)}\`. See the [Game API overview](./) for status levels.`, "");
  return lines.join("\n");
}

function overviewPage(doc, bySub, opaque, source) {
  const b = doc.build ?? {};
  const rows = [...bySub].map(([sub, list]) => {
    const n = (k) => list.filter((e) => e.kind === k).length;
    return `| [${sub}](./${sub}.md) | \`<swofty/game/${sub}.hpp>\` | ${n("func")} | ${n("struct")} | ${n("data")} | ${n("site") + n("call") + n("vtable")} |`;
  });
  return [
    "---",
    "title: Game API",
    "description: Functions, structs and patch sites of F1 25 that native plugins can use.",
    "---",
    "",
    marker,
    "",
    "# Game API",
    "",
    "The game API lists the functions, structs and patch sites of F1 25 that [native plugins](/reference/addons/native-plugins) can use. Each subsystem has its own header and its own page.",
    "",
    "## Build",
    "",
    "| | |",
    "|---|---|",
    `| Executable | \`${b.exe ?? "F1_25.exe"}\` |`,
    b.sha256 ? `| SHA-256 | \`${b.sha256}\` |` : null,
    b.size ? `| Size | ${b.size.toLocaleString("en-AU")} bytes |` : null,
    b.image_base ? `| Image base | \`${b.image_base}\` |` : null,
    "",
    "Bindings are found by signature at load time. The RVAs on each page are for this build.",
    "",
    "## Status",
    "",
    "| Status | Meaning |",
    "|---|---|",
    "| **stable** | Level L3, confirmed by a passing trace test |",
    "| **experimental** | Level L2, or L3 without a passing test, with an agreeing verification |",
    "",
    "## Subsystems",
    "",
    "| Subsystem | Header | Functions | Structs | Data | Sites |",
    "|---|---|---|---|---|---|",
    ...rows,
    "",
    "Include `<swofty/game.hpp>` for every subsystem.",
    "",
    opaque.size ? "## Opaque types\n\nThese types are known by name only. Use them through pointers.\n\n" + [...opaque].sort().map((t) => `\`${t}\``).join(", ") + "\n" : null,
    "## Regenerating",
    "",
    "These pages are generated. To refresh them after the bindings change:",
    "",
    "```sh",
    "node docs/scripts/gen-reference.mjs --root /path/to/checkout",
    "```",
    "",
    `Last generated from \`${source}\`.`,
    "",
  ]
    .filter((l) => l !== null)
    .join("\n");
}

function stubPage(bindingsPath) {
  return [
    "---",
    "title: Game API",
    "description: Functions, structs and patch sites of F1 25 that native plugins can use.",
    "---",
    "",
    marker,
    "",
    "# Game API",
    "",
    "The game API reference lists the functions, structs and patch sites that [native plugins](/reference/addons/native-plugins) can use, one page per subsystem.",
    "",
    "It has not been generated yet. It is built from `bindings.json` and the headers in `native/include/swofty/`:",
    "",
    "```sh",
    "node docs/scripts/gen-reference.mjs --root /path/to/checkout",
    "```",
    "",
    `The generator looked for \`${path.basename(bindingsPath)}\` and found nothing.`,
    "",
  ].join("\n");
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const outputs = new Map();
  let sidebar = { subsystems: [] };

  if (!fs.existsSync(opts.bindings)) {
    const existing = fs.existsSync(sidebarFile) ? JSON.parse(fs.readFileSync(sidebarFile, "utf8")) : { subsystems: [] };
    if (existing.subsystems.length && !opts.stub) {
      console.error(`no bindings at ${opts.bindings}; keeping the generated pages. Pass --root, or --stub to replace them.`);
      process.exit(1);
    }
    outputs.set(path.join(outDir, "index.md"), stubPage(opts.bindings));
  } else {
    const doc = JSON.parse(fs.readFileSync(opts.bindings, "utf8"));
    const { structs, opaque, buildSha } = parseHeaders(opts.include);
    const build = doc.build?.sha256 ?? buildSha ?? "";
    const source = `${path.relative(opts.root, opts.bindings).split(path.sep).join("/")}`;
    const bySub = new Map();
    const add = (e) => {
      if (!bySub.has(e.subsystem)) bySub.set(e.subsystem, []);
      bySub.get(e.subsystem).push(e);
    };
    for (const b of doc.bindings ?? []) add(b);
    for (const s of structs.values()) add(s);
    const sorted = new Map([...bySub].sort(([a], [b]) => a.localeCompare(b)));
    for (const [sub, list] of sorted) {
      list.sort((a, b) => kindOrder.indexOf(a.kind) - kindOrder.indexOf(b.kind) || a.id.localeCompare(b.id));
      outputs.set(path.join(outDir, `${sub}.md`), subsystemPage(sub, list, { structs, subsystem: sub, build }, source));
    }
    outputs.set(path.join(outDir, "index.md"), overviewPage(doc, sorted, opaque, source));
    sidebar = {
      build,
      subsystems: [...sorted].map(([sub, list]) => ({
        name: sub,
        link: `/reference/game/${sub}`,
        entries: list.map((e) => ({ name: e.id, kind: e.kind, status: e.status ?? null, link: `/reference/game/${sub}#${e.id}` })),
      })),
    };
  }
  outputs.set(sidebarFile, JSON.stringify(sidebar, null, 2) + "\n");

  const stale = [];
  if (fs.existsSync(outDir)) {
    for (const f of fs.readdirSync(outDir)) {
      const p = path.join(outDir, f);
      if (f.endsWith(".md") && !outputs.has(p) && fs.readFileSync(p, "utf8").includes(marker)) stale.push(p);
    }
  }

  if (opts.check) {
    const changed = [...outputs].filter(([p, text]) => !fs.existsSync(p) || fs.readFileSync(p, "utf8") !== text).map(([p]) => p);
    for (const p of [...changed, ...stale]) console.error(`out of date: ${path.relative(docsDir, p)}`);
    process.exit(changed.length || stale.length ? 1 : 0);
  }

  fs.mkdirSync(outDir, { recursive: true });
  for (const [p, text] of outputs) fs.writeFileSync(p, text);
  for (const p of stale) fs.rmSync(p);
  console.log(
    sidebar.subsystems.length
      ? `wrote ${sidebar.subsystems.length} subsystem pages from ${opts.bindings}`
      : `no bindings at ${opts.bindings}; wrote the stub page`,
  );
}

main();
